/**
 * GridSense AI - Alert Controller
 */

const { firestoreStore } = require("../config/firebase");

exports.getAlerts = (req, res, next) => {
  try {
    res.json({
      success: true,
      count: firestoreStore.alerts.length,
      data: firestoreStore.alerts
    });
  } catch (err) {
    next(err);
  }
};

exports.createAlert = (req, res, next) => {
  try {
    const { type, severity, message, neighbourhoodId = "area_a" } = req.body;
    const newAlert = {
      id: "alt_" + Date.now(),
      type: type || "ENERGY GAP DETECTED",
      severity: severity || "WARNING",
      neighbourhoodId,
      timestamp: new Date().toISOString(),
      message: message || "Automated telemetry alert generated by GridSense Engine."
    };
    firestoreStore.alerts.unshift(newAlert);
    res.status(201).json({ success: true, data: newAlert });
  } catch (err) {
    next(err);
  }
};
